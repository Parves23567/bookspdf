export async function fetchBooksConfig() {
  try {
    const res = await fetch('/data/books.json');
    if (res.ok) {
      const data = await res.json();
      if (Array.isArray(data) && data.length > 0) {
        return data;
      }
    }
  } catch (err) {
    console.warn('Using bundled initial books config fallback:', err);
  }
  return INITIAL_BOOKS;
}
